const fs = require('node:fs');
const assert = require('node:assert/strict');
const {JSDOM} = require('jsdom');
const source = fs.readFileSync(process.argv[2], 'utf8');
const helper = source.slice(source.indexOf('// Authentication progress stays'), source.indexOf('function viewSignin(q){return{title:'));
const signin = source.split('\n').find(l => l.startsWith('function viewSignin(q){return{title:'));
const auth = source.split('\n').find(l => l.startsWith('const Auth={get(){return Live.user?'));
assert(helper && signin && auth);
const deferred = () => { let resolve, reject; const promise = new Promise((a,b)=>{resolve=a;reject=b;}); return {promise,resolve,reject}; };
const tick = () => new Promise(r=>setTimeout(r,10));
async function run() {
  const dom = new JSDOM('<main id="main"></main>', {url:'https://example.test/#/signin',runScripts:'outside-only',pretendToBeVisual:true});
  const w=dom.window;
  let login=deferred(), refresh=deferred(), logout=deferred(), calls=[], messages=[];
  w.Live={config:{auth:true},user:null}; w.ROLES={admin:{}};
  w.api=(path,data)=>{calls.push([path,data]);return (path==='/login'?login:logout).promise;};
  w.Engine={refresh:()=>refresh.promise,clear:()=>calls.push(['clear'])};
  w.Local=w.Sess={del:()=>{}};
  w.$=s=>w.document.querySelector(s); w.toast=m=>messages.push(m);
  const render=()=>{w.document.querySelector('#main').textContent=w.Live.user?'Dashboard ready':'Website ready';};
  w.addEventListener('hashchange',render);
  w.go=path=>{if(w.location.hash==='#'+path)render();else w.location.hash=path;};
  w.eval(auth+'\n'+helper+'\n'+signin+'\nwindow.subject={Auth,AuthProgress,viewSignin,signOutWithProgress};');
  const mount=()=>{const v=w.subject.viewSignin({});w.$('#main').innerHTML=v.html;v.mount();w.$('#u').value='test@example.test';w.$('#p').value='test-only';};
  mount();
  const form=w.$('#secure-login'), button=form.querySelector('button');
  const pending=form.onsubmit({preventDefault(){}});
  assert.match(w.$('#auth-progress').textContent,/Signing in…/); assert(button.disabled);
  await form.onsubmit({preventDefault(){}}); assert.equal(calls.length,1,'blocks duplicate sign-in');
  login.resolve({user:{role:'admin'}});await tick();
  assert(w.$('#auth-progress'),'loading persists through dashboard data refresh');
  assert.equal(w.location.hash,'#/signin');
  refresh.resolve();await pending;
  assert.equal(w.$('#main').textContent,'Dashboard ready');assert.equal(w.$('#auth-progress'),null);
  const out=w.subject.signOutWithProgress('Signed out.');
  assert.match(w.$('#auth-progress').textContent,/Signing out…/);
  assert.equal(w.location.hash,'#/app/retail','does not navigate before logout');
  await w.subject.signOutWithProgress('duplicate');
  assert.equal(calls.filter(c=>c[0]==='/logout').length,1);
  logout.resolve({});await out;
  assert.equal(w.location.hash,'#/');assert.equal(w.$('#main').textContent,'Website ready');assert.equal(w.$('#auth-progress'),null);
  login=deferred();mount();const failed=w.$('#secure-login').onsubmit({preventDefault(){}});
  login.reject(new Error('Invalid credentials'));await failed;
  assert.equal(w.$('#login-error').textContent,'Invalid credentials');assert.equal(w.$('#auth-progress'),null);
  assert.equal(w.$('#secure-login button').disabled,false);assert.equal(w.$('#secure-login button').textContent,'Sign in');
  logout=deferred();const badOut=w.subject.signOutWithProgress('never');logout.reject(new Error('Connection unavailable'));await badOut;
  assert.equal(w.$('#auth-progress'),null);assert.equal(messages.at(-1),'Connection unavailable');
  assert.equal(calls[0][1].email,'test@example.test');
  dom.window.close();console.log('PASS: delayed sign-in, dashboard readiness, delayed sign-out, duplicate actions, and error recovery');
}
run().catch(e=>{console.error(e);process.exitCode=1;});

